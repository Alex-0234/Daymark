const group = (category: string, rows: Row[]): Exercise[] =>
  rows.map(([id, name, tier, requires, modifiers, branch = 'standard', unit = 'reps']) => ({
    id,
    name,
    category,
    branch,
    tier,
    unit,
    requires,
    modifiers,
    isExplosive: branch === 'power'
  }))

